  sabotages++;
  check("SABOTAGE filterKeys: an unknown key is dropped and listed as source/category/key; a category left empty disappears; duplicates fold",
    f["*"]?.join() === "poe_budget" && !("switches" in f) && dropped.join() === "src/*/not_a_field,src/switches/no_such_key", { f, dropped });
