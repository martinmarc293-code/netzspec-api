// tests/source-fields.test.ts — proof for src/pipeline/build-source-fields.ts and the file it
// generates, data/schema/source-fields.json (the capability matrix the gap ledger reasons from).
//
//   npx tsx tests/source-fields.test.ts                                            pure half
//   NETZSPEC_DB=test DATABASE_URL_TEST=postgres://…/netzspec_test5 npx tsx tests/source-fields.test.ts   + the database half
//
// Pure half (no database):
//   * the committed file lists ONLY keys the dictionary defines, every list is non-empty, and every
//     enabled lookup source (queue.ts LOOKUP_TASK) has at least one key or a recorded reason for
//     none (its inventory was read and mapped no spec field, with the labels listed);
//   * the derivation from a real label inventory yields dictionary keys and nothing else; the
//     golden files yield the switch and server keys they hold;
//   * SABOTAGE on the checker: an unknown key, an empty list, an enabled lookup source with no key
//     and no explanation — each named in the problems; the explained case is NOT a problem.
// Database half (skipped with a MISS-free notice when NETZSPEC_DB is not `test`, so `npm test`
// stays pure; run it with the flag to prove it):
//   * build() against the test database — no html_table facts — falls back to the golden files for
//     the Cisco sources and reproduces the committed inventory-derived lists exactly (deterministic);
//   * the test registry has cdw ENABLED with no inventory, so the built file's own problems name
//     cdw — the "forgot to inventory a source" refusal, fired for real;
//   * loadSourceFields loads the committed file (rows inserted, no unknown key);
//   * SABOTAGE: a file with an unknown key under provantage is rejected by loadSourceFields naming
//     `provantage/*/not_a_field`, and no row for it exists afterwards.
