// scripts/universe/apply-inheritance-classes.mjs
//
//   node scripts/universe/apply-inheritance-classes.mjs <journal.jsonl>            dry run
//   node scripts/universe/apply-inheritance-classes.mjs <journal.jsonl> --commit    write
//
// Give every generated field an inheritance class, or none of the family-scoped data can land.
//
// WHY THIS IS THE LAST BLOCKER
// specMerge.canInherit ends with:
//     return { ok: false, cls: "unknown", reason: `${fieldKey} has no inheritance class` };
// so a field with no class is refused by default. All 232 generated fields were unclassified.
// That matters more than it sounds: Cisco states most facts ONCE PER SERIES, so the corpus
// holds 29,703 MAPPED family-scoped facts against 5,144 SKU-scoped ones. Refusing them all
// discards the majority of everything extracted.
//
// WHY NOT A HEURISTIC
// The obvious rule -- "has a unit, therefore per-model" -- is wrong in both directions.
// sdwan_capable has no unit and is safely series-level; display has no unit and is the primary
// physical difference between endpoint models. poe_at_support is a plain Yes/No and is the
// single most dangerous field to inherit, because PoE vs non-PoE is the main SKU split inside
// a switch series and inheriting "Yes" would declare every model PoE+.
//
// The classes were assigned per field from real sample values, with an explicit instruction to
// prefer B when torn: an unclassified field merely costs coverage, a wrong class A silently
// writes one model's value onto every sibling in the series.
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const journal = process.argv[2];
if (!journal) { console.error("usage: apply-inheritance-classes.mjs <journal.jsonl> [--commit]"); process.exit(2); }
const COMMIT = process.argv.includes("--commit");
const OUT = path.join(ROOT, "lib/inheritClasses.generated.ts");

const classifications = [];
for (const line of fs.readFileSync(journal, "utf8").split("\n")) {
  if (!line.trim()) continue;
  try {
    const r = JSON.parse(line);
    if (r.type === "result" && Array.isArray(r.result?.classifications)) {
      classifications.push(...r.result.classifications);
    }
  } catch { /* partial */ }
}

const gen = fs.readFileSync(path.join(ROOT, "lib/fieldSchema.generated.ts"), "utf8");
const genKeys = new Set([...gen.matchAll(/^ {2}([a-z0-9_]+): \{ key:/gm)].map((m) => m[1]));

const A = [], B = [], C = [];
const notes = {};
const skipped = [];
const seen = new Set();
for (const c of classifications) {
  const k = String(c.field_key || "");
  if (!genKeys.has(k)) { skipped.push({ k, why: "not a generated field" }); continue; }
  if (seen.has(k)) continue;
  seen.add(k);
  notes[k] = String(c.why || "").replace(/\s+/g, " ").slice(0, 140);
  const cls = String(c.class || "").trim().toUpperCase();
  if (cls === "A") A.push(k);
  else if (cls === "C") C.push(k);
  else if (cls === "B") B.push(k);
  // Anything else is left OUT entirely, which means "refused by default" — the safe answer.
  else skipped.push({ k, why: `unrecognised class ${JSON.stringify(c.class)}` });
}
const unclassified = [...genKeys].filter((k) => !seen.has(k));

console.log(`classified: ${seen.size} of ${genKeys.size} generated fields`);
console.log(`  A (safely inheritable) : ${A.length}`);
console.log(`  B (never inherited)    : ${B.length}`);
console.log(`  C (conditional)        : ${C.length}`);
console.log(`  left unclassified      : ${unclassified.length} — refused by default, which is safe`);
if (skipped.length) console.log(`  skipped: ${skipped.length} (${skipped.slice(0, 4).map((s) => s.k + ": " + s.why).join("; ")})`);

// Sanity check with teeth: any field carrying a unit that was called safely inheritable is
// worth a second look, because a measured quantity almost never is. Report rather than
// silently drop — the classifier saw the values and may be right (a series-wide voltage, say).
const unitOf = {};
for (const m of gen.matchAll(/^ {2}([a-z0-9_]+): \{ key: "[^"]+", de: "[^"]*", en: "[^"]*", type: "[^"]*"(?:, unit: "([^"]*)")?/gm)) {
  if (m[2]) unitOf[m[1]] = m[2];
}
const suspicious = A.filter((k) => unitOf[k]);
if (suspicious.length) {
  console.log(`\n⚠ class A fields that carry a UNIT (a measured quantity is rarely series-wide) — review:`);
  for (const k of suspicious) console.log(`   ${k} [${unitOf[k]}] — ${notes[k]}`);
}

if (!COMMIT) { console.log("\n(dry run — pass --commit to write)"); process.exit(0); }

const emit = (name, keys) => [
  `export const GENERATED_CLASS_${name}: string[] = [`,
  ...keys.sort().map((k) => `  ${JSON.stringify(k)},   // ${notes[k] || ""}`),
  "];",
  "",
];
const ts = [
  "// lib/inheritClasses.generated.ts — GENERATED by scripts/universe/apply-inheritance-classes.mjs.",
  "// Do not edit by hand; re-run the classifier.",
  "//",
  "// specMerge.canInherit refuses any field with no inheritance class, so without this file the",
  "// 29,703 mapped family-scoped facts — the majority of everything the corpus yields, because",
  "// Cisco states most facts once per SERIES — are all discarded.",
  "//",
  "// A = property of the series, identical for every member (protocols, standards, software",
  "//     feature sets, certifications).",
  "// B = NEVER inherited; varies between members and inheriting it corrupts the whole series",
  "//     (anything physical or electrical, port counts, PoE support, capacities).",
  "// C = inheritable only when the document carries no per-SKU value (environmental envelopes,",
  "//     architectural scale limits).",
  "//",
  "// Assigned per field from real sample values, biased towards B: an unclassified field only",
  "// costs coverage, a wrong A silently writes one model's value onto every sibling.",
  "",
  ...emit("A", A),
  ...emit("B", B),
  ...emit("C", C),
];
fs.writeFileSync(OUT, ts.join("\n"));
console.log(`\nwrote ${OUT}`);
console.log("NEXT: specMerge.ts must union these into INHERIT_CLASS_A/B/C (one hand edit).");
